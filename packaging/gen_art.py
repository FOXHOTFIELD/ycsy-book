"""Regenerate ``src/ycsy/art.py`` from the source PNG.

    pip install pillow
    python packaging/gen_art.py path/to/whale.png

The picture is flagged down to a handful of character cells and packed into
half blocks: one cell carries two vertical pixels (``▀`` with the upper pixel as
foreground and the lower one as background). Only the *outside* background is
dropped - a white belly surrounded by the body stays.
"""

from __future__ import annotations

import pathlib
import sys
from collections import deque

from PIL import Image

COLS = 28
WHITE = (255, 255, 255)
# 0 is "leave the terminal background alone"
PALETTE = {0: None, 1: "#ffffff", 2: "#556ef6", 3: "#18255d", 4: "#c5e0fc"}


def outside_mask(image: Image.Image) -> list:
    """True for background pixels reachable from the border."""
    width, height = image.size
    pixels = image.load()
    outside = [[False] * width for _ in range(height)]
    queue = deque()

    def push(x: int, y: int) -> None:
        if not outside[y][x] and pixels[x, y] == WHITE:
            outside[y][x] = True
            queue.append((x, y))

    for x in range(width):
        push(x, 0)
        push(x, height - 1)
    for y in range(height):
        push(0, y)
        push(width - 1, y)
    while queue:
        x, y = queue.popleft()
        for nx, ny in ((x - 1, y), (x + 1, y), (x, y - 1), (x, y + 1)):
            if 0 <= nx < width and 0 <= ny < height:
                push(nx, ny)
    return outside


def nearest(rgb: tuple) -> str:
    best, best_distance = 1, None
    for slot, value in PALETTE.items():
        if not value:
            continue
        distance = sum((int(value[i:i + 2], 16) - c) ** 2 for i, c in zip((1, 3, 5), rgb))
        if best_distance is None or distance < best_distance:
            best, best_distance = slot, distance
    return str(best)


def build(path: pathlib.Path) -> str:
    image = Image.open(path).convert("RGB")
    width, height = image.size
    outside = outside_mask(image)

    mask = Image.new("L", (width, height))
    mask.putdata([0 if outside[y][x] else 255 for y in range(height) for x in range(width)])

    rows_px = max(2, round(height * COLS / width / 2) * 2)      # even, for half blocks
    small = image.resize((COLS, rows_px), Image.NEAREST)
    small_mask = mask.resize((COLS, rows_px), Image.NEAREST)

    top_rows, bottom_rows = [], []
    for cell_y in range(rows_px // 2):
        top_row, bottom_row = [], []
        for cell_x in range(COLS):
            for pixel_y, sink in ((cell_y * 2, top_row), (cell_y * 2 + 1, bottom_row)):
                if small_mask.getpixel((cell_x, pixel_y)) < 128:
                    sink.append("0")
                else:
                    sink.append(nearest(small.getpixel((cell_x, pixel_y))))
        top_rows.append("".join(top_row))
        bottom_rows.append("".join(bottom_row))

    rows = len(top_rows)
    return (
        '"""Pixel art for the bottom-right corner of the main screen.\n'
        "\n"
        "Generated by ``packaging/gen_art.py`` from a %dx%d PNG: flagged down to\n"
        "%d columns; each character cell carries two vertical pixels via half blocks.\n"
        '``0`` means "leave the terminal background alone".\n'
        '"""\n'
        "\n"
        "# slot -> colour, 0 = transparent\n"
        "PALETTE = %r\n"
        "\n"
        "TOP = [\n%s\n]\n"
        "\n"
        "BOTTOM = [\n%s\n]\n"
        % (width, height, COLS, PALETTE,
           "\n".join('    "%s",' % row for row in top_rows),
           "\n".join('    "%s",' % row for row in bottom_rows))
    )


def main(argv: list) -> int:
    if len(argv) != 2:
        print(__doc__)
        return 2
    source = pathlib.Path(argv[1])
    target = pathlib.Path(__file__).resolve().parent.parent / "src" / "ycsy" / "art.py"
    target.write_text(build(source), encoding="utf-8", newline="\n")
    print("wrote %s (%d columns)" % (target, COLS))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
